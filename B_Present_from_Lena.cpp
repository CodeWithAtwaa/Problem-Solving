int main()
{
    int n;
    cin >> n;

    for (int i = 0; i <= 2 * n; i++)
    {
        int k = (i <= n ? i : 2 * n - i);

        for (int s = 0; s < 2 * (n - k); s++)
            cout << " ";

        for (int j = 0; j <= k; j++)
        {
            if (j > 0)
                cout << " ";
            cout << j;
        }

        for (int j = k - 1; j >= 0; j--)
        {
            cout << " " << j;
        }

        cout << "\n";
    }
}
