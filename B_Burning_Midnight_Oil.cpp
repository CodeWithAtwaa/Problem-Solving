bool can(ll v, ll k, ll n)
{
    ll sum = v;
    ll exp = 1;
    while (v / (ll)(pow(k, exp)) > 0)
    {
        sum += v / (ll)(pow(k, exp));
        if (sum >= n)
            return true;
        exp++;
    }
    return sum >= n;
}
int main()
{
    ios;

    ll n, k;
    cin >> n >> k;

    int l = 1;
    int r = n;
    ll ans = n;
    while (l <= r)
    {
        ll mid = l + (r - l) / 2;
        if (can(mid, k, n))
        {
            ans = mid;
            r = mid - 1;
        }
        else
        {
            l = mid + 1;
        }
    }
    cout << ans << endl;
}
